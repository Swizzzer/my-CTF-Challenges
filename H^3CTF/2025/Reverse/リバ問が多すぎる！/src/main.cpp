#include "camellia.hpp"
#include <cstdint>
#include <iomanip>
#include <iostream>
#include <string>
#include <vector>
int level1() {
  std::string pt;
  std::cout << "Input the flag > ";
  std::getline(std::cin, pt);
  std::vector<uint8_t> pt_bytes(pt.begin(), pt.end());
  std::vector<uint8_t> key = {0x13, 0x37, 0xde, 0x34, 0x4d, 0xf5, 0x6c, 0x97,
                              0x38, 0x09, 0xba, 0xbf, 0xca, 0xfd, 0xee, 0xdf};
  std::vector<uint8_t> iv = {0xe3, 0xdc, 0xba, 0x98, 0x76, 0x54, 0x32, 0x10,
                             0x01, 0x23, 0xd5, 0xdd, 0x89, 0xac, 0xca, 0xdb};
  std::vector<uint8_t> ct = CamelliaStreamEncrypt(key, iv, pt_bytes);
  std::vector<uint8_t> flag_ct = {
      0x5a, 0x84, 0x71, 0x52, 0xa3, 0x94, 0xb6, 0xa7, 0xad, 0x81, 0x65,
      0xc6, 0xa5, 0xb2, 0x61, 0x8d, 0x59, 0xb8, 0xec, 0x38, 0x1a, 0x8c,
      0xf7, 0xe8, 0x48, 0x8e, 0xa0, 0x5a, 0xb0, 0x69, 0xd0, 0xc1, 0x61};

  if (ct.size() != flag_ct.size()) {
    std::cout << "Wrong length!" << std::endl;
    return 1;
  }
  for (size_t i = 0; i < ct.size(); ++i) {
    if (ct[i] != flag_ct[i]) {
      std::cout << "Wrong!" << std::endl;
      std::cout << "Your ciphertext: ";
      for (uint8_t byte : ct) {
        std::cout << std::hex << std::setw(2) << std::setfill('0')
                  << static_cast<int>(byte);
      }
      std::cout << std::dec << std::endl;
      return 1;
    }
  }
  std::cout << "Correct!" << std::endl;
  return 0;
}
int level2() {
  std::vector<std::array<uint8_t, 4>> flag_hash = {
      {0x1c, 0x9b, 0xaa, 0x69}, {0x1c, 0xe1, 0x62, 0x2f},
      {0x9f, 0xe1, 0x73, 0xbb}, {0x60, 0xe5, 0x73, 0xf8},
      {0x9d, 0xe1, 0x78, 0xf8}, {0x9d, 0xaa, 0x09, 0xe6},
      {0x9e, 0xaa, 0xa5, 0xa7}, {0xeb, 0xa2, 0xa5, 0xd2},
      {0x4a, 0xc4, 0x9e, 0xd2}, {0x4a, 0x16, 0x7e, 0xdc},
      {0x41, 0x16, 0xcf, 0xfe}, {0xd5, 0x12, 0xcf, 0xd6},
      {0x9c, 0xb0, 0xd4, 0xd6}, {0x9c, 0xc1, 0x3b, 0xec},
      {0x6d, 0xc1, 0xf3, 0xab}, {0x5b, 0x31, 0xf3, 0x73},
      {0x8d, 0x7e, 0xe4, 0x73}, {0x8d, 0xd0, 0x6e, 0x65},
      {0x9c, 0xd0, 0x2f, 0xc1}, {0xcd, 0xfc, 0x2f, 0xbc},
      {0x3e, 0x98, 0x3a, 0xbc}, {0x3e, 0xf0, 0x24, 0x8a},
      {0xcf, 0xf0, 0xd0, 0xd1}, {0x9a, 0xe8, 0xd0, 0x16},
      {0x9e, 0x3d, 0xb9, 0x16}, {0x9e, 0xbd, 0xeb, 0x68}};

  std::string pt;
  std::cout << "Input the flag > ";
  std::getline(std::cin, pt);
  std::vector<uint8_t> pt_bytes(pt.begin(), pt.end());
  std::vector<std::array<uint8_t, 4>> hash = CamelliaHashVector(pt_bytes);

  if (hash.size() != flag_hash.size()) {
    std::cout << "Wrong length!" << std::endl;
    return 1;
  }
  for (size_t i = 0; i < hash.size(); ++i) {
    if (hash[i] != flag_hash[i]) {
      std::cout << "Wrong!" << std::endl;
      return 1;
    }
  }
  std::cout << "Correct!" << std::endl;
  return 0;
}
int main(int argc, char *argv[]) {
  if (argc < 2) {
    std::cout << "Usage: " << argv[0] << " <level>" << std::endl;
    return 1;
  }
  int level = std::stoi(argv[1]);
  switch (level) {
  case 1:
    return level1();
  case 2:
    return level2();
  default:
    std::cout << "Invalid level!" << std::endl;
    return 1;
  }
}
